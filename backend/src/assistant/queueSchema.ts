// Phase 4 schema: additive columns on assistant_requests, plus audit events and execution attempts.
// Safe to run on every startup: each step checks before it changes anything.
import { Knex } from 'knex';
import { LEGACY_STATUS } from './lifecycle';

// SQLite's standard column check does not list generated columns, so it reads the extended table listing instead
async function hasGeneratedColumn(db: Knex, table: string, column: string): Promise<boolean> {
  if ((db.client as any).config?.client === 'mysql2') return db.schema.hasColumn(table, column);
  const rows: any[] = await db.raw(`PRAGMA table_xinfo(${table})`);
  return rows.some((r: any) => r.name === column);
}

// Index names are checked before creating, so the schema step can run again safely on both databases
async function hasIndex(db: Knex, table: string, name: string): Promise<boolean> {
  if ((db.client as any).config?.client === 'mysql2') {
    const rows: any[] = await db.raw('SHOW INDEX FROM ?? WHERE Key_name = ?', [table, name]).then((r: any) => r[0]);
    return rows.length > 0;
  }
  const rows: any[] = await db.raw(`PRAGMA index_list(${table})`);
  return rows.some((r: any) => r.name === name);
}

async function addColumn(db: Knex, name: string, build: (t: Knex.AlterTableBuilder) => void) {
  if (!(await db.schema.hasColumn('assistant_requests', name))) {
    await db.schema.alterTable('assistant_requests', build);
  }
}

export async function ensureQueueSchema(db: Knex): Promise<void> {
  await addColumn(db, 'version', (t) => { t.integer('version').notNullable().defaultTo(0); });
  await addColumn(db, 'priority', (t) => { t.integer('priority').notNullable().defaultTo(100); });
  await addColumn(db, 'confirm_code', (t) => { t.string('confirm_code', 8).nullable(); });
  await addColumn(db, 'confirmation_expires_at', (t) => { t.timestamp('confirmation_expires_at').nullable(); });
  await addColumn(db, 'confirmed_by', (t) => { t.integer('confirmed_by').nullable(); });
  await addColumn(db, 'confirmed_at', (t) => { t.timestamp('confirmed_at').nullable(); });
  await addColumn(db, 'queue_expires_at', (t) => { t.timestamp('queue_expires_at').nullable(); });
  await addColumn(db, 'execution_attempts', (t) => { t.integer('execution_attempts').notNullable().defaultTo(0); });
  await addColumn(db, 'next_attempt_at', (t) => { t.timestamp('next_attempt_at').nullable(); });
  await addColumn(db, 'locked_by', (t) => { t.string('locked_by', 64).nullable(); });
  await addColumn(db, 'locked_until', (t) => { t.timestamp('locked_until').nullable(); });
  await addColumn(db, 'failure_kind', (t) => { t.string('failure_kind', 20).nullable(); });
  // The unique index below means the database itself refuses a second PROCESSING request for the same employee.
  // Generated by the database from the status: the employee's id while PROCESSING, NULL otherwise. Every write path
  // (including a direct SQL update) therefore obeys the unique index below.
  if (!(await hasGeneratedColumn(db, 'assistant_requests', 'processing_user_key'))) {
    if ((db.client as any).config?.client === 'mysql2') {
      // VIRTUAL: MySQL refuses to add a STORED generated column to a table that has foreign keys
      await db.raw("ALTER TABLE assistant_requests ADD COLUMN processing_user_key INT UNSIGNED GENERATED ALWAYS AS (CASE WHEN status = 'PROCESSING' THEN loop_user_id END) VIRTUAL");
    } else {
      await db.raw("ALTER TABLE assistant_requests ADD COLUMN processing_user_key INTEGER GENERATED ALWAYS AS (CASE WHEN status = 'PROCESSING' THEN loop_user_id END) VIRTUAL");
    }
  }
  if (!(await hasIndex(db, 'assistant_requests', 'assistant_one_processing_per_employee'))) {
    await db.schema.alterTable('assistant_requests', (t) => { t.unique(['processing_user_key'], 'assistant_one_processing_per_employee'); });
  }
  await addColumn(db, 'result_summary', (t) => { t.string('result_summary', 500).nullable(); });

  // One request per confirmation code; a code can never point at two requests
  try { await db.schema.alterTable('assistant_requests', (t) => { t.unique(['confirm_code'], 'assistant_requests_confirm_code_unique'); }); }
  catch { /* already present */ }
  try { await db.schema.alterTable('assistant_requests', (t) => { t.index(['status', 'priority', 'created_at'], 'assistant_requests_queue_idx'); }); }
  catch { /* already present */ }

  if (!(await db.schema.hasTable('assistant_request_events'))) {
    await db.schema.createTable('assistant_request_events', (t) => {
      t.increments('id').primary();
      t.string('request_id', 36).notNullable();
      t.string('conversation_key', 200).notNullable();
      t.integer('loop_user_id').nullable();
      t.string('event', 40).notNullable();
      t.string('from_state', 30).nullable();
      t.string('to_state', 30).nullable();
      t.string('execution_id', 36).nullable();
      t.string('detail', 300).nullable();
      t.timestamp('created_at').defaultTo(db.fn.now());
      t.index(['request_id']);
    });
  }
  if (!(await db.schema.hasTable('assistant_executions'))) {
    await db.schema.createTable('assistant_executions', (t) => {
      t.string('id', 36).primary();
      t.string('request_id', 36).notNullable();
      t.integer('attempt').notNullable();
      t.string('idempotency_key', 80).notNullable();
      t.string('status', 20).notNullable();        // running | succeeded | failed_transient | failed_terminal | interrupted
      t.string('error', 300).nullable();
      t.timestamp('started_at').defaultTo(db.fn.now());
      t.timestamp('finished_at').nullable();
      t.unique(['request_id', 'attempt']);
      t.index(['status']);
    });
  }

  // Administrative actions (retry, identity revocation): who did what, when. Read-only through the admin API.
  if (!(await db.schema.hasTable('assistant_admin_audit'))) {
    await db.schema.createTable('assistant_admin_audit', (t) => {
      t.increments('id').primary();
      t.integer('actor_id').notNullable();
      t.string('action', 40).notNullable();
      t.string('target', 80).nullable();
      t.string('detail', 300).nullable();
      t.timestamp('created_at').defaultTo(db.fn.now());
      t.index(['created_at']);
    });
  }

  // Ticket changes made by the assistant. Written in the same transaction as the change.
  // The unique (request_id, operation) index stops a retried execution from repeating a change.
  if (!(await db.schema.hasTable('assistant_ticket_audit'))) {
    await db.schema.createTable('assistant_ticket_audit', (t) => {
      t.increments('id').primary();
      t.string('request_id', 64).notNullable();
      t.string('execution_id', 64).nullable();
      t.integer('loop_user_id').notNullable();
      t.integer('task_id').notNullable();
      t.string('operation', 40).notNullable();
      t.text('before_json').nullable();
      t.text('after_json').nullable();
      t.timestamp('created_at').defaultTo(db.fn.now());
      t.unique(['request_id', 'operation']);
      t.index(['task_id']);
    });
  }

  // Phase 3 statuses → Phase 4 lifecycle names (idempotent)
  for (const [legacy, next] of Object.entries(LEGACY_STATUS)) {
    await db('assistant_requests').where({ status: legacy }).update({ status: next });
  }
}
